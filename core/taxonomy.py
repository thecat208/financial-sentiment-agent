"""
受控词表：集中定义"事件类型""情感维度""信息来源类型"三份词表，
供 Prompt、解析、存储、知识图谱等各处复用，避免同一份分类标准散落多处维护不一致。

事件类型：受控词表使跨公司/跨时间的标准化统计（GROUP BY）成为可能，自由文本没法可靠聚合。
情感维度：把笼统的情感分拆成多维度分别打分，"业绩超预期但管理层被质疑"这类
矛盾信号不会被糊成一个中间值。
信息来源类型：不同来源权威性差异很大（机构公告 vs 散户情绪代理指标），
需要一个正交于"事件类型"的维度标注"这条信息大致有多可信"，供用户/下游过滤或参考。
"""

# 事件类型受控词表。覆盖常见金融舆情事件大类，选择性地比原始自由文本更粗一点，
# 保证每个类目都有足够样本量做统计（类目太细会导致每类样本太少，统计没意义）。
# 需要新增类目时，在这里加一项即可，Prompt和解析逻辑都会自动跟着变，
# 不需要改其他文件。
EVENT_CATEGORIES = [
    "业绩预告",   # 业绩预告/预增预减/财报发布
    "并购重组",   # 并购/资产重组/资产收购剥离
    "高管变更",   # 高管/董监事变动
    "诉讼仲裁",   # 诉讼/仲裁/合同纠纷
    "监管处罚",   # 立案调查/行政处罚/监管问询
    "评级调整",   # 分析师评级上调/下调
    "分红送转",   # 分红/送股/转增
    "股权变动",   # 股东增减持/股权质押/解禁
    "行业政策",   # 行业监管政策/产业政策变化
    "产品与业务", # 新产品/业务合作/订单中标
    "其他",       # 兜底类目，不属于以上任何一类时用这个，不要留空
]

# 默认兜底事件类型：LLM解析失败、或输出的类目不在受控词表里时使用
DEFAULT_EVENT_CATEGORY = "其他"

# 情感维度受控词表。四个维度覆盖金融舆情里最常被单独关注的角度：
#   业绩     —— 财务表现、营收利润、业绩预期兑现情况
#   管理层   —— 高管/董监事的可信度、稳定性、治理相关的正负面评价
#   行业前景 —— 所在行业/赛道的景气度、政策环境、竞争格局
#   合规风险 —— 监管/法律/诉讼/信息披露等合规层面的风险
# 需要新增维度（比如"供应链""ESG"）时，在这里加一项，
# chains/prompts/analysis_prompt.py 的 AnalysisResult 需要同步加一个对应字段。
DIMENSIONS = ["业绩", "管理层", "行业前景", "合规风险"]

# 每个维度分数的取值范围说明，供Prompt和校验共用
DIMENSION_SCORE_RANGE = (-1.0, 1.0)


def normalize_event_type(event_type: str) -> str:
    """把任意event_type归一化到受控词表内；不在词表里的一律归到兜底类目"""
    if event_type in EVENT_CATEGORIES:
        return event_type
    return DEFAULT_EVENT_CATEGORY


def clip_dimension_score(score: float) -> float:
    """维度分数裁剪到合法范围，防止LLM偶尔输出超范围的值"""
    lo, hi = DIMENSION_SCORE_RANGE
    try:
        return max(lo, min(hi, float(score)))
    except (TypeError, ValueError):
        return 0.0


def default_dimension_scores() -> dict:
    """全零的维度分数，用于解析失败时的兜底结果"""
    return {d: 0.0 for d in DIMENSIONS}


# 事件类型关键词粗分类规则。
# 只给轻量模型的"快速通道"用——快速通道遇到明确命中某类关键词的文本时，
# 用这份粗规则给一个大致的event_type，省去这一步的LLM调用；命中不明确时
# 快速通道整体会因为置信度不够而升级到LLM，LLM路径完全不用这份词表，
# 用的是Prompt里更细致的分类判断。词表刻意从简，不追求覆盖率。
EVENT_KEYWORD_RULES = {
    "业绩预告": ["业绩预告", "业绩预增", "业绩预减", "净利润增长", "营收增长", "财报"],
    "并购重组": ["并购", "重组", "收购", "资产剥离"],
    "高管变更": ["董事长", "总经理", "董事会秘书", "高管变动", "辞职", "聘任"],
    "诉讼仲裁": ["诉讼", "仲裁", "合同纠纷"],
    "监管处罚": ["立案调查", "行政处罚", "监管问询", "警示函", "违规"],
    "评级调整": ["评级上调", "评级下调", "评级调整"],
    "分红送转": ["分红", "送股", "转增"],
    "股权变动": ["增持", "减持", "股权质押", "解禁"],
    "行业政策": ["产业政策", "行业监管", "政策调整"],
    "产品与业务": ["新产品", "业务合作", "中标", "签署", "订单"],
}


def guess_event_type_by_keywords(text: str) -> str:
    """
    粗规则猜事件类型，命中第一个匹配的类目就返回；一个都不命中返回兜底类目。
    只用于轻量模型快速通道，不追求精确——精确分类是LLM Prompt的职责。
    """
    for category, keywords in EVENT_KEYWORD_RULES.items():
        if any(kw in text for kw in keywords):
            return category
    return DEFAULT_EVENT_CATEGORY


# ============================================================
# 信息来源类型受控词表
# ============================================================
# source_type 是新增的正交维度，与具体来源名称区分：
#   source      —— 具体来源名称（"巨潮资讯网""东方财富-千股千评"这种，自由文本，用于溯源）
#   source_type —— 来源类型（受控词表，用于统计/可信度分级/下游按可信度加权）
# 两者不是一回事：同一个 source_type（如"新闻资讯"）可能对应很多不同的具体 source。
SOURCE_TYPES = [
    "机构公告",   # 交易所/巨潮资讯网等公开渠道的上市公司公告全文
    "新闻资讯",   # 财经媒体新闻报道（原有RSS采集，也是历史数据的默认值）
    "研报",       # 券商/机构研究报告（预留，暂无采集器，接入方式见 ingestion/social_source.py 顶部说明）
    "社交媒体",   # 散户情绪源（当前用千股千评市场热度数据作为合规代理指标，见 ingestion/social_source.py）
    "其他",       # 真正无法归类时的兜底
]

# 没有显式标注来源类型时的默认值：历史数据和多数尚未细分来源的调用方
# 实际上都是新闻类数据，用"新闻资讯"而不是"其他"作为默认值更符合实际分布。
DEFAULT_SOURCE_TYPE = "新闻资讯"

# 来源可信度分级。机构公告/研报权威性最高，社交媒体最低（热度不代表事实准确性）。
# 分级只做展示和下游加权参考，不改变现有的情感分析逻辑，避免过度设计。
SOURCE_CREDIBILITY = {
    "机构公告": "高",
    "研报": "高",
    "新闻资讯": "中",
    "社交媒体": "低",
    "其他": "中",
}


def normalize_source_type(source_type: str) -> str:
    """把任意source_type归一化到受控词表内；不在词表里（含None/空字符串）一律归到默认类型"""
    if source_type in SOURCE_TYPES:
        return source_type
    return DEFAULT_SOURCE_TYPE


def get_source_credibility(source_type: str) -> str:
    """按来源类型查可信度分级，查不到给"中"（既不特别信任也不特别怀疑的中性默认值）"""
    return SOURCE_CREDIBILITY.get(normalize_source_type(source_type), "中")
